"""Closed-book probe (no retrieval) of main (Qwen3-32B-FP8) and small (Qwen3-8B) over benchmark item files, 4 option permutations each
(perm 0 = original order; perms 1-3 = deterministic re-permutations of `otter.evaluation.hard_gen.permute`; prompt `otter_hard_closed_v1`,
temperature 0, thinking off). Resumable; raw answers in runs/closed_book_probe/raw_<role>.jsonl (keyed by id+perm+item hash).
Writes the sidecar benchmarks/otter_hard/closed_book_probe.jsonl (+ closed_book_probe.README.md) with
  id, split, main_acc, small_acc, n_perm_main, n_perm_small, closed_book_hard
closed_book_hard = main_acc <= 0.5 AND small_acc <= 0.5   (rule is computed from closed-book answers only, never from a system's retrieval results)
  .venv/bin/python scripts/eval/closed_book_probe.py --bench benchmarks/otter_hard/dev.jsonl benchmarks/otter_hard/test.jsonl [--workers-main 6 --workers-small 12]
Re-run on the re-assembled / reviewed sets by passing the new files (rows of unchanged items are reused; the sidecar keeps ids of ALL files passed)."""
import argparse, json, sys, threading, hashlib
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT))
from otter.evaluation.hard_gen import check_closed  # noqa: E402
from otter.llm.interface import get_llm  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--bench", nargs="+", required=True)
ap.add_argument("--workers-main", type=int, default=6)
ap.add_argument("--workers-small", type=int, default=12)
ap.add_argument("--roles", nargs="+", default=["main", "small"])
ap.add_argument("--out", default=str(ROOT / "benchmarks/otter_hard/closed_book_probe.jsonl"))
ap.add_argument("--perms", type=int, default=4)
a = ap.parse_args()
items = {}
for bp in a.bench:
    for l in open(ROOT / bp if not Path(bp).is_absolute() else bp):
        if l.strip():
            r = json.loads(l)
            if r.get("answer"):
                items[r["id"]] = r
h = lambda r: hashlib.sha1(json.dumps([r["question"], r["options"], r["answer"]], ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:12]
raw_dir = ROOT / "runs/closed_book_probe"; raw_dir.mkdir(parents=True, exist_ok=True)
res = {}
for role in a.roles:
    p = raw_dir / f"raw_{role}.jsonl"
    done = {}
    if p.exists():
        for l in open(p):
            if l.strip():
                r = json.loads(l); done[(r["id"], r["perm"], r["h"])] = r
    llm = get_llm(role); lock = threading.Lock()
    todo = [(i, k) for i, r in items.items() for k in range(a.perms) if (i, k, h(r)) not in done]
    print(role, "todo", len(todo), "of", len(items) * a.perms, flush=True)

    def one(t):
        i, k = t; r = items[i]
        c = {"options": r["options"], "answer": r["answer"], "cand_id": i, "domain": r.get("domain"), "grade": r.get("grade"), "question": r["question"]}
        try:
            o = check_closed(c, llm, k); row = {"id": i, "perm": k, "h": h(r), "pred": o["answer"], "gold": r["answer"], "conf": o["confidence"]}
        except Exception as e:
            row = {"id": i, "perm": k, "h": h(r), "pred": None, "gold": r["answer"], "conf": None, "error": f"{type(e).__name__}: {e}"[:200]}
        with lock, open(p, "a") as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
        return row
    w = a.workers_main if role == "main" else a.workers_small
    with ThreadPoolExecutor(w) as ex:
        for n, _ in enumerate(ex.map(one, todo), 1):
            if n % 200 == 0:
                print(role, n, "/", len(todo), flush=True)
    done = {}
    for l in open(p):
        if l.strip():
            r = json.loads(l)
            if "error" not in r or (r["id"], r["perm"], r["h"]) not in done:
                done[(r["id"], r["perm"], r["h"])] = r
    res[role] = done
rows = []
for i, r in items.items():
    row = {"id": i, "split": r.get("split")}
    for role in a.roles:
        ps = [res[role].get((i, k, h(r))) for k in range(a.perms)]
        ok = [x for x in ps if x and "error" not in x]
        row[f"{role}_acc"] = round(sum(x["pred"] == x["gold"] for x in ok) / len(ok), 3) if ok else None
        row[f"n_perm_{role}"] = len(ok)
    row["closed_book_hard"] = (all(row.get(f"{rl}_acc") is not None and row[f"{rl}_acc"] <= 0.5 for rl in ("main", "small"))
                               if len(a.roles) == 2 else None)
    rows.append(row)
with open(a.out, "w") as f:
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")
Path(a.out).with_suffix(".README.md").write_text(f"""# closed_book_probe sidecar

Per-item closed-book (no retrieval, no textbook) accuracy of Qwen3-32B-FP8 (`main_acc`) and Qwen3-8B (`small_acc`) over {a.perms} option
permutations (perm 0 = original order, perms 1-3 = deterministic re-permutations; prompt `otter_hard_closed_v1`, temperature 0, thinking off).
Generated by `scripts/eval/closed_book_probe.py`; raw answers in `runs/closed_book_probe/raw_*.jsonl`.

Subsets (defined from closed-book answers only, so they are not tuned on any retrieval system's results):
* `closed_book_hard` = `main_acc <= 0.5` AND `small_acc <= 0.5`  (both models get at most 2 of 4 permutations right)
* `closed_book_easy` = not `closed_book_hard`

Items: {len(rows)} (files: {', '.join(a.bench)}). Re-run after every re-assembly of the benchmark.
""")
n = sum(1 for r in rows if r["closed_book_hard"])
print("items", len(rows), "closed_book_hard", n)
